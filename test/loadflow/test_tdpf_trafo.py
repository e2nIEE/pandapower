def test_three_winding_hot_spot_uses_library_defaults():
    """Without per-winding overrides the hot-spot follows the IEC defaults, not the documented 1.2/20.

    The documentation sets ``winding_oil_gradient=20`` and ``hot_spot_fac=1.2`` per winding. Those are
    optional specifications that pandapower does not expose, so the library defaults 17 K and 1.3
    are used. The top-oil temperature is unaffected by this, which is why it still matches exactly.
    """
    net = _three_winding_docs_net(THREEW_AMBIENT_C + THREEW_AMBIENT_SURCHARGE_K, current_a=500.0)
    calculate_transformer_temperatures(net)

    top_oil = net.res_trafo3w.at[0, TOP_OIL_COLUMN]
    for winding, column in zip(("lv", "mv", "hv"), HOT_SPOT_3W_COLUMNS):
        nominal_load = THREEW_DOCS_NOM_LOAD_A[winding]
        expected = top_oil + 1.3 * 17.0 * (500.0 / nominal_load) ** 1.3
        assert net.res_trafo3w.at[0, column] == pytest.approx(expected, rel=1e-9)
        # the documented value used the larger 20 K gradient and the smaller 1.2 factor
        documented = THREEW_DOCS_HOT_SPOT_STEADY_C[column]
        assert net.res_trafo3w.at[0, column] != pytest.approx(documented, rel=1e-6)

"""Tests of the transformer thermal model integration into the TDPF.

The transformer temperatures are post-processing results of the optional `transformer-thermal-model`
library. These tests cover the nameplate adapter, the physical correctness of the results and the
lifecycle (columns only appear when the calculation actually ran).

The "documentation examples" section additionally reproduces the examples published in the official
library documentation (https://alliander-opensource.github.io/transformer-thermal-model/). Its
reference values are the numbers printed there, not numbers generated by pandapower, so they guard the
integration against a wrong nameplate mapping and against drift in the external library.

The top-oil temperature depends only on the *mandatory* nameplate data -- no-load loss, load loss,
the nominal currents and the ambient temperature -- which pandapower maps one to one. Its documented
values are therefore reproduced exactly.

The hot-spot temperature additionally depends on the optional per-transformer and per-winding
specifications (``winding_oil_gradient``, ``hot_spot_fac``, ``time_const_windings`` ...). pandapower
does not expose these as input columns and leaves them at the library defaults, so the documented
hot-spot values are only reproduced where the documentation itself used those defaults (the quick
start). For the three winding example the documentation overrides them per winding, and the test
checks the value that follows from the pandapower defaults instead.
"""


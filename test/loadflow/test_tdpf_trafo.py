def test_quickstart_transient_profile_matches_documentation():
    """Chaining the top-oil temperature reproduces the documented transient profile.

    The tracker only carries the top-oil temperature across the time steps, because the library does
    not accept an initial winding hot-spot increase. The top-oil temperature therefore matches the
    documentation exactly, while the hot-spot can deviate by a fraction of a kelvin during the first
    hours after the cold start.
    """
    net = _quickstart_net()
    tracker = TransformerThermalTracker()

    top_oil, hot_spot = [], []
    for _ in range(len(QUICKSTART_TOP_OIL_HEAD_C) - 1):
        tracker.run(net, dt_minutes=QUICKSTART_DT_MINUTES)
        top_oil.append(net.res_trafo.at[0, TOP_OIL_COLUMN])
        hot_spot.append(net.res_trafo.at[0, HOT_SPOT_COLUMN])

    assert np.allclose(top_oil, QUICKSTART_TOP_OIL_HEAD_C[1:], rtol=1e-9)
    assert np.allclose(hot_spot, QUICKSTART_HOT_SPOT_HEAD_C[1:], atol=0.5)



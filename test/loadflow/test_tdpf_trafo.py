@pytest.mark.parametrize("tdpf_value", [False, np.nan])
def test_unselected_line_values_are_not_validated(tdpf_value):
    """Only the values of the selected TDPF lines are validated.

    An ordinary line that never opted in must not trigger a "required columns missing" warning just
    because its thermal parameter is NaN. The transformer is still calculated, which is the whole point
    of allowing ``tdpf=True`` on a grid whose lines are not part of the thermal calculation.
    """
    net = _lines_and_trafo_net()
    net.line["tdpf"] = tdpf_value
    net.line["r_theta_kelvin_per_mw"] = np.nan

    runpp(net, tdpf=True, tdpf_update_r_theta=False)

    assert np.isfinite(net.res_trafo.at[0, TEMPERATURE_COLUMN])


def test_selected_line_without_thermal_parameters_raises():
    """A line that opts in but has a NaN thermal parameter must still raise."""
    net = _lines_and_trafo_net()
    net.line["tdpf"] = True
    net.line["r_theta_kelvin_per_mw"] = np.nan

    with pytest.raises(UserWarning, match="required columns"):
        runpp(net, tdpf=True, tdpf_update_r_theta=False)


def test_missing_tdpf_column_still_raises():
    """The selection column itself is required; it is not silently assumed to be False."""
